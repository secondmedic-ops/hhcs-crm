// ---------- toasts
const ToastCtx = createContext(() => {});
export const useToast = () => useContext(ToastCtx);
export function ToastProvider({ children }) {
  const [items, setItems] = useState([]);
  const push = useCallback((msg, kind = 'info') => {
    const id = Math.random();
    setItems((x) => [...x, { id, msg: String(msg?.message || msg), kind }]);
    setTimeout(() => setItems((x) => x.filter((i) => i.id !== id)), kind === 'error' ? 6500 : 3500);
  }, []);
  const api = useCallback((m, k) => push(m, k), [push]);
  api.ok = (m) => push(m, 'ok');
  api.error = (m) => push(m, 'error');
  return (
    <ToastCtx.Provider value={api}>
      {children}
      <div className="toasts" role="status">
        {items.map((t) => (
          <div key={t.id} className={`toast ${t.kind}`}>
            <Icon name={t.kind === 'error' ? 'alert' : t.kind === 'ok' ? 'check' : 'note'} />
            <span>{t.msg}</span>
          </div>
        ))}
      </div>
    </ToastCtx.Provider>
  );
}

// run an async action with busy state + toast on error
export function useAction() {
  const toast = useToast();
  const [busy, setBusy] = useState(false);
  const run = useCallback(async (fn, okMsg) => {
    setBusy(true);
    try { const r = await fn(); if (okMsg) toast.ok(okMsg); return r; }
    catch (e) { toast.error(e.message || String(e)); return undefined; }
    finally { setBusy(false); }
  }, [toast]);
  return [run, busy];
}

