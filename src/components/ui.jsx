export const Badge = ({ kind = '', children, dot, title, className = '' }) => (
  <span className={`badge ${kind} ${className}`} title={title}>{dot && <span className="dot" />}{children}</span>
);

const STAGE_KIND = { enquiry: 'info', pricing: 'plum', booking: 'accent', deployment: 'warn', completion: 'accent', payment: 'plum', closure: 'info', closed: 'ok', cancelled: '' };
export const StageBadge = ({ stage }) => <Badge kind={STAGE_KIND[stage]}>{STAGE_LABEL[stage] || stage}</Badge>;

export const SlaBadge = ({ state }) => state === 'breached' ? <Badge kind="danger" dot>SLA breached</Badge>
  : state === 'at_risk' ? <Badge kind="warn" dot>At risk</Badge> : <Badge kind="ok" dot>Within SLA</Badge>;

export const PriorityBadge = ({ p }) => (p === 'urgent' ? <Badge kind="danger">Urgent</Badge> : null);

export const AiTag = ({ children = 'AI' }) => <span className="ai-tag" title="Generated by AI · review before acting"><Icon name="ai" size={10} stroke={1.6} />{children}</span>;

export function Countdown({ due, label, compact }) {
  const now = useNow(1000);
  const c = countdown(due, now);
  if (!c) return null;
  const kind = c.overdue ? 'danger' : c.seconds < 180 ? 'warn' : 'outline';
  return (
    <Badge kind={kind} title={`${SLA_LABEL[label] || label || 'SLA'} due ${new Date(due).toLocaleTimeString('en-IN', { timeZone: 'Asia/Kolkata' })}`}>
      <Icon name="clock" size={11} /> <span className="mono">{c.text}</span>{!compact && label ? <span> · {SLA_LABEL[label] || label}</span> : null}
    </Badge>
  );
}

