export function Skeleton({ lines = 3, height }) {
  if (height) return <div className="sk" style={{ height }} />;
  return <div>{Array.from({ length: lines }, (_, i) => <div key={i} className="sk sk-line" style={{ width: `${92 - ((i * 17) % 40)}%` }} />)}</div>;
}
export function TableSkeleton({ rows = 6, cols = 5 }) {
  return (
    <table className="t"><tbody>
      {Array.from({ length: rows }, (_, r) => (
        <tr key={r}>{Array.from({ length: cols }, (_, c) => <td key={c}><div className="sk" style={{ height: 11, width: `${50 + ((r * 7 + c * 13) % 45)}%` }} /></td>)}</tr>
      ))}
    </tbody></table>
  );
}

