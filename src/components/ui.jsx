export function Segmented({ options, value, onChange }) {
  return (
    <div className="btn-group">
      {options.map((o) => { const [v, l] = Array.isArray(o) ? o : [o, o]; return <button key={v} type="button" className={`btn sm ${value === v ? 'on' : ''}`} onClick={() => onChange(v)}>{l}</button>; })}
    </div>
  );
}

export function Confirm({ title, children, confirmLabel = 'Confirm', danger, onConfirm, onClose, busy, needReason, reasonLabel = 'Reason' }) {
  const [reason, setReason] = useState('');
  return (
    <Modal title={title} onClose={onClose} footer={<>
      <Button onClick={onClose}>Cancel</Button>
      <Button kind={danger ? 'danger' : 'primary'} disabled={busy || (needReason && !reason.trim())} onClick={() => onConfirm(reason)}>{confirmLabel}</Button>
    </>}>
      {children}
      {needReason && <Field label={reasonLabel} className="mt-12"><Textarea value={reason} onChange={(e) => setReason(e.target.value)} autoFocus /></Field>}
    </Modal>
  );
}
